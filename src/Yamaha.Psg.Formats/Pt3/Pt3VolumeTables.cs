namespace Yamaha.Psg.Formats.Pt3;

/// <summary>
/// Combines a sample step's (post-amplitude-slide) amplitude (0-15) and a channel's volume (0-15,
/// from pattern command $C1-$CF) into a final 0-15 DAC level, via a lookup table indexed
/// [volume, amplitude] - not a linear formula. The original milestone-11.1 guess
/// (<c>round(amplitude*volume/15)</c>) was wrong; these exact tables were confirmed by diffing our
/// interpreter's register output against a real Vortex Tracker PSG export of a real track (see
/// docs/PT3_TABLES.md) and cross-checked against a behavioral reference implementation
/// (benbaker76/PT3PlayBlazor - read only, no code copied; the *table values* are a factual, publicly
/// re-derivable measurement of tracker behavior, not copyrightable expression, same status as the
/// AY/YM DAC tables in DAC_TABLES.md).
/// </summary>
