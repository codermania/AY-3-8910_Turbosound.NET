    };

    /// <param name="version">The PT3 version digit (e.g. 7 for "ProTracker 3.7") - selects which table.</param>
    public static int Combine(int amplitude, int volume, int version)
    {
        byte[,] table = version <= 4 ? Table_UpTo34 : Table_35Plus;
        return table[Math.Clamp(volume, 0, 15), Math.Clamp(amplitude, 0, 15)];
    }
}
